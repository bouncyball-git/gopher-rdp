const (
	dotW   = 5 // glyph width in dots
	dotH   = 7 // glyph height in dots
	dotGap = 1 // gap between dots (in dot-pixels)
)

// drawDigitalText renders s in a dot-matrix LED style, centered on screen.
func drawDigitalText(screen *ebiten.Image, s string, clr color.Color) {
	sw, sh := screen.Bounds().Dx(), screen.Bounds().Dy()

	// Scale dots so total text height ≈ 1/16 of screen height.
	dotSize := sh / (dotH * 16)
	if dotSize < 2 {
		dotSize = 2
	}
	cellW := dotSize + dotGap
	cellH := dotSize + dotGap
	charW := dotW*cellW + cellW // 5 dots + 1 dot gap between chars
	totalW := len(s)*charW - cellW
	totalH := dotH * cellH

	// Create dot pixel (reuse for all dots).
	dot := ebiten.NewImage(dotSize, dotSize)
	dot.Fill(clr)

	// Center on screen.
	ox := (sw - totalW) / 2
	oy := (sh - totalH) / 2

	for ci, ch := range []byte(s) {
		glyph, ok := digitalFont[ch]
		if !ok {
			// uppercase fallback
			if ch >= 'a' && ch <= 'z' {
				glyph, ok = digitalFont[ch-32]
			}
			if !ok {
				continue
			}
		}
		cx := ox + ci*charW
		for row := 0; row < dotH; row++ {
			bits := glyph[row]
			for col := 0; col < dotW; col++ {
				if bits&(1<<(4-col)) != 0 {
					op := &ebiten.DrawImageOptions{}
					op.GeoM.Translate(
						float64(cx+col*cellW),
						float64(oy+row*cellH),
					)
					screen.DrawImage(dot, op)
				}
			}
		}
	}

	// Draw dim dots for "off" LEDs to complete the effect.
	dimClr := color.NRGBA{0x1A, 0x0E, 0x00, 0xFF}
	dimDot := ebiten.NewImage(dotSize, dotSize)
	dimDot.Fill(dimClr)

	for ci, ch := range []byte(s) {
		glyph, ok := digitalFont[ch]
		if !ok {
			if ch >= 'a' && ch <= 'z' {
				glyph, ok = digitalFont[ch-32]
			}
			if !ok {
				continue
			}
		}
		cx := ox + ci*charW
		for row := 0; row < dotH; row++ {
			bits := glyph[row]
			for col := 0; col < dotW; col++ {
				if bits&(1<<(4-col)) == 0 {
					op := &ebiten.DrawImageOptions{}
					op.GeoM.Translate(
						float64(cx+col*cellW),
						float64(oy+row*cellH),
					)
					screen.DrawImage(dimDot, op)
				}
			}
		}
	}

	// Dispose scratch images so they don't leak across frames.
	dot.Deallocate()
	dimDot.Deallocate()
}

// drawDigitalOverlay fills the screen black and draws a centered digital message.
func drawDigitalOverlay(screen *ebiten.Image, msg string) {
	screen.Fill(color.Black)

	// Dim scanline overlay for CRT feel — horizontal lines every 2px.
	sw, sh := screen.Bounds().Dx(), screen.Bounds().Dy()
	scanline := ebiten.NewImage(sw, 1)
	scanline.Fill(color.NRGBA{0, 0, 0, 0x18})
	for y := 0; y < sh; y += 2 {
		op := &ebiten.DrawImageOptions{}
		op.GeoM.Translate(0, float64(y))
		screen.DrawImage(scanline, op)
	}
	scanline.Deallocate()

	drawDigitalText(screen, msg, color.NRGBA{0xCC, 0x70, 0x00, 0xFF})
}
